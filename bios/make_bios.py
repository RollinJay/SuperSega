#!/usr/bin/env python3
"""Build the MasterDrive BIOS and write it where each implementation reads it.

usage: make_bios.py            assemble and write the three outputs
       make_bios.py --check    assemble and check that the committed outputs match

The source is bios/masterdrive_bios.asm (with its includes), assembled by z80asm 1.8
(Bas Wijnen; the Ubuntu and Debian package 'z80asm'), plus the font, bios/font6x8.txt,
which this script turns into an assembler include. The outputs, all committed:

  bios/masterdrive_bios.rom          the image, padded with $FF to 8 KB (the BIOS ROM's size,
                                     Technical Reference section 2); larger is refused
  pocket-core/rtl/mdr_bios.hex       the same bytes, one per line, for $readmemh
  emulator/masterdrive-emulator.html the same bytes as base64, between the markers
                                     BIOS_BEGIN and BIOS_END

CI runs --check, so the committed outputs always come from the committed source.
"""
import base64
import os
import re
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(HERE, 'masterdrive_bios.asm')
FONT = os.path.join(HERE, 'font6x8.txt')
ROM = os.path.join(HERE, 'masterdrive_bios.rom')
HEX = os.path.join(ROOT, 'pocket-core', 'rtl', 'mdr_bios.hex')
PAGE = os.path.join(ROOT, 'emulator', 'masterdrive-emulator.html')
BIOS_SIZE = 0x2000
BEGIN = '/* BIOS_BEGIN: generated by bios/make_bios.py from bios/; do not edit */'
END = '/* BIOS_END */'


def font_include():
    """The font as 'db' lines: 8 bytes a character, bits 7-3 the five columns."""
    glyphs, cur = {}, None
    for line in open(FONT).read().splitlines():
        m = re.match(r'^([0-9A-F]{2}) ', line)
        if m:
            cur = int(m.group(1), 16)
            glyphs[cur] = []
        elif cur is not None and len(line) == 5 and set(line) <= set('#.'):
            glyphs[cur].append(line)
    out = ['; generated by make_bios.py from font6x8.txt: printable ASCII $20-$7E, 8 bytes each']
    for c in range(0x20, 0x7F):
        rows = glyphs.get(c)
        if rows is None or len(rows) != 8:
            sys.exit(f'font6x8.txt: character ${c:02X} is missing or not 8 rows')
        b = [sum(1 << (7 - i) for i, p in enumerate(r) if p == '#') for r in rows]
        out.append('\tdb ' + ', '.join(f'0x{v:02X}' for v in b) + f'\t; ${c:02X}')
    return '\n'.join(out) + '\n'


def check_names():
    """z80asm 1.8 reads a name that starts with a register and an underscore (B_IDX, C_X)
    as the register itself: `ld c,B_IDX` assembles as `ld c,b`, silently. Refuse them."""
    bad = []
    for fn in sorted(os.listdir(HERE)):
        if fn.endswith(('.asm', '.inc')):
            for n, line in enumerate(open(os.path.join(HERE, fn)).read().splitlines(), 1):
                m = re.match(r'^([A-Za-z_][A-Za-z0-9_]*):', line)
                if m and re.match(r'(?i)(a|b|c|d|e|h|l|i|r|af|bc|de|hl|ix|iy|ixh|ixl|iyh|iyl|sp)_', m.group(1)):
                    bad.append(f'{fn}:{n}: {m.group(1)}')
    if bad:
        sys.exit('names z80asm would read as a register (rename them):\n  ' + '\n  '.join(bad))


def assemble():
    check_names()
    if not shutil.which('z80asm'):
        sys.exit('z80asm not found: install the z80asm package (version 1.8)')
    v = subprocess.run(['z80asm', '--version'], capture_output=True, text=True)
    if 'version 1.8' not in v.stdout + v.stderr:
        sys.exit('z80asm 1.8 is needed (another version may assemble different bytes):\n' + v.stdout + v.stderr)
    with tempfile.TemporaryDirectory() as tmp:
        open(os.path.join(tmp, 'font.inc'), 'w').write(font_include())
        out = os.path.join(tmp, 'bios.bin')
        r = subprocess.run(['z80asm', '-I', tmp, '-I', HERE, '-o', out, SRC], capture_output=True, text=True)
        if r.returncode != 0 or not os.path.exists(out):
            sys.exit('z80asm failed:\n' + r.stdout + r.stderr)
        img = bytearray(open(out, 'rb').read())
    if not img:
        sys.exit('the BIOS assembled to nothing')
    if len(img) > BIOS_SIZE:
        sys.exit(f'the BIOS is {len(img)} bytes; the BIOS ROM holds {BIOS_SIZE}')
    return bytes(img + b'\xFF' * (BIOS_SIZE - len(img)))


def hex_text(img):
    return ''.join(f'{b:02X}\n' for b in img)


def page_block(img):
    b64 = base64.b64encode(img).decode()
    lines = [b64[i:i + 120] for i in range(0, len(b64), 120)]
    return BEGIN + '\nconst MD_BIOS_B64=\n' + '+\n'.join(f"'{x}'" for x in lines) + ';\n' + END


def page_with(img, page):
    i, j = page.find(BEGIN), page.find(END)
    if i < 0 or j < i:
        sys.exit('emulator page: the BIOS_BEGIN/BIOS_END markers are missing')
    return page[:i] + page_block(img) + page[j + len(END):]


def main():
    check = '--check' in sys.argv[1:]
    img = assemble()
    page = open(PAGE).read()
    want = {ROM: img, HEX: hex_text(img).encode(), PAGE: page_with(img, page).encode()}
    if check:
        bad = [p for p, data in want.items() if not os.path.exists(p) or open(p, 'rb').read() != data]
        for p in bad:
            print('out of date:', os.path.relpath(p, ROOT))
        if bad:
            sys.exit('run bios/make_bios.py and commit its outputs')
        print(f'BIOS outputs match the source ({len(img)} bytes)')
        return
    for p, data in want.items():
        open(p, 'wb').write(data)
    print(f'wrote the {len(img)}-byte image to the ROM, the hex file and the page')


if __name__ == '__main__':
    main()
